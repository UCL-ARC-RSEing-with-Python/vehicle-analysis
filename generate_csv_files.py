"""This script generates the sample CSV files for cars, vans, and hgvs that come with the repository.

If you have accidentally changed any of the `cars.csv`, `vans.csv`, or `hgvs.csv` files (found inside
the `data/` directory) you can run this script to re-generate those files.
You can also generate these files using this script if they are not already present in the
repository (as the `.gitignore` is set to ignore `.csv` files).

Fake data is generated by drawing random values from a "reasonable" range, for each part of the
specification for the vehicles.
- Cars: X-sections 2-2.4, 7-char license plates, engine power 80-150 * 1000, RRP 25-75, drag coefficients ~0.15-0.3,
- Vans: X-sections 2.5-4, 7-char license plates, engine power 75-135 * 1000, RRP 40-95, drag coefficients ~0.25-0.5,
- HGVs: X-sections 9-10, 4-digit license plates, engine power 290-447 * 1000, RRP 100-200, drag coefficients ~0.5-1.0
"""

from datetime import datetime, timedelta
from pathlib import Path
from string import ascii_uppercase, digits

import numpy as np
import pandas as pd

DATA_DIR = Path(__file__).parent / "data"
RANGES = {
    "cars": {
        "x-section": (2.0, 2.4),
        "rrp": (25.0, 75.0),
        "plate-len": 7,
        "plate-chars": ascii_uppercase + digits,
        "power": (80.0, 150.0),
        "coeffs": (0.15, 0.3),
    },
    "vans": {
        "x-section": (2.5, 4.0),
        "rrp": (40.0, 95.0),
        "plate-len": 7,
        "plate-chars": ascii_uppercase + digits,
        "power": (75.0, 135.0),
        "coeffs": (0.25, 0.5),
    },
    "hgvs": {
        "x-section": (9.0, 10.0),
        "rrp": (100.0, 200.0),
        "plate-len": 4,
        "plate-chars": digits,
        "power": (290.0, 447.0),
        "coeffs": (0.5, 1.0),
    },
}

if __name__ == "__main__":
    # Avoid path errors later on when saving
    DATA_DIR.mkdir(exist_ok=True, parents=True)

    # Fix RNG so that generated files are the same
    seed = 0
    rng = np.random.Generator(np.random.PCG64(seed=seed))

    # Oldest vehicle will be around 5 years old...
    today = datetime.now().replace(hour=0, minute=0, second=0, microsecond=0)
    manufacture_start = datetime.now().replace(
        year=today.year - 5, hour=0, minute=0, second=0, microsecond=0
    )
    days_to_choose_from = (today - manufacture_start).days

    n_vehs = {
        "cars": 25,
        "vans": 16,
        "hgvs": 7,
    }

    for veh_type, veh_ranges in RANGES.items():
        n_of_this_vehicle = n_vehs[veh_type]

        data = {}
        data["Plate"] = [
            "".join(
                rng.choice(
                    list(veh_ranges["plate-chars"]), size=veh_ranges["plate-len"]
                )
            )
            for _ in range(n_of_this_vehicle)
        ]
        data["RRP"] = rng.uniform(*veh_ranges["rrp"], size=n_of_this_vehicle).round(
            decimals=3
        )
        data["Engine Power"] = rng.uniform(
            *(1000 * x for x in veh_ranges["power"]), size=n_of_this_vehicle
        ).round(decimals=2)
        data["Drag Coefficient"] = rng.uniform(
            *veh_ranges["coeffs"], size=n_of_this_vehicle
        ).round(decimals=3)
        data["Cross Section"] = rng.uniform(
            *veh_ranges["x-section"], size=n_of_this_vehicle
        ).round(decimals=1)
        data["Manufacture Date"] = [
            (manufacture_start + timedelta(days=x)).strftime("%Y-%m-%d")
            for x in rng.uniform(0.0, days_to_choose_from, size=n_of_this_vehicle)
        ]

        pd.DataFrame(data).to_csv(DATA_DIR / f"{veh_type}.csv", index=False)
